export function translate(value, language="en") {
  const original=String(value);
  if(language!=="sq") return original;
  const trim=original.trim();
  if (!trim) return original;
  let result=sq[trim];
  if(result===undefined){
    for(const [re,fn] of patterns){const m=trim.match(re);if(m){result=fn(...m.slice(1));break;}}
  }
  if(result===undefined)return original;
  const i=original.indexOf(trim);
  return original.slice(0,i)+result+original.slice(i+trim.length);
}
const textSource = new WeakMap();
const attrsSource = new WeakMap();
export function localize(root, language="en") {
  if (!root || typeof document==="undefined") return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  let node;
  while((node=walker.nextNode())){
    if(node.parentElement?.closest("script,style,svg,.leaflet-tile-pane"))continue;
    const previous=textSource.get(node);
    const current=node.nodeValue;
    const source=previous && current===previous.last ? previous.source : current;
    const next=translate(source,language);
    textSource.set(node,{source,last:next});
    if(current!==next)node.nodeValue=next;
  }
  const nodes=[root,...(root.querySelectorAll?.("[aria-label],[title],[placeholder],[alt]")||[])];
  for(const el of nodes){
    if(!el?.getAttribute || el.closest?.(".leaflet-tile-pane"))continue;
    const prev=attrsSource.get(el)||{};
    for(const attr of ["aria-label","title","placeholder","alt"]){
      if(!el.hasAttribute(attr))continue;
      const current=el.getAttribute(attr);
      const source=prev[attr] && current===prev[attr].last?prev[attr].source:current;
      const next=translate(source,language);
      prev[attr]={source,last:next};
      if(current!==next)el.setAttribute(attr,next);
    }
    attrsSource.set(el,prev);
  }
}
