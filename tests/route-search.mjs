import assert from "node:assert/strict";
import fs from "node:fs";
globalThis.matchMedia=()=>({matches:false,addEventListener(){}});
const {state}=await import("../assets/js/state.js");
const {findStop,findRoutes,stopSuggestions}=await import("../assets/js/routes.js");
const {fleetCount}=await import("../assets/js/simulation.js");
const lines=JSON.parse(fs.readFileSync(new URL("../data/lines.json",import.meta.url),"utf-8"));
const stops=JSON.parse(fs.readFileSync(new URL("../data/stops.geojson",import.meta.url),"utf-8"));
const routes=JSON.parse(fs.readFileSync(new URL("../data/routes.geojson",import.meta.url),"utf-8"));
state.lines=lines;state.stops=stops.features;state.routes=routes.features;
const a=findStop("rrethi 24h"),b=findStop("furra saranda");
assert(a && /maxi.*24h/i.test(a.properties.name),"Rrethi 24h alias finds mapped stop");
assert(b && /saranda/i.test(b.properties.name),"Furra Saranda finds mapped stop");
const options=findRoutes("rrethi 24h","furra saranda");
assert(options.length>0,"One-transfer route available for the sample search");
assert(options[0].type==="transfer"||options[0].type==="direct","Route structured");
assert(options[0].type==="direct" || options[0].transfer.meters<=400,"Transfer walk is within 400 m");
assert(stopSuggestions("saranda").some(s=>s.properties.name.includes("Saranda")),"Local autocomplete matches");
assert(state.routes.length>=9,"Nine OSM demo route segments available");
assert(state.lines.every(l=>fleetCount(l.id)>0),"All routes can simulate vehicles");
const html=fs.readFileSync(new URL("../index.html",import.meta.url),"utf-8");
const main=fs.readFileSync(new URL("../assets/js/main.js",import.meta.url),"utf-8");
const screens=fs.readFileSync(new URL("../assets/js/ui/screens.js",import.meta.url),"utf-8");
assert(main.includes('navigate("settings")'),"Settings navigates to an in-app route");
assert(!main.includes(".showModal()"),"Old settings modal removed");
assert(screens.includes("Valid until midnight"),"Daily validity text updated");
assert(!screens.includes("Opens the official wallet website in a new tab."),"Redundant wallet footer removed");
assert(screens.includes("is1-ssl.mzstatic.com"),"Official wallet artwork included");
assert(!html.includes('<dialog id="settings-dialog"'),"No settings overlay");
console.log("Route-name matching, walking transfers, settings, and ticket assertions passed:", options.map(x=>x.id));
