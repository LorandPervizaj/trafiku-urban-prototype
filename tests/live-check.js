async (page)=>{
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  await page.setViewportSize({width:390,height:844});
  const response=await page.goto("https://lorandpervizaj.github.io/trafiku-urban-prototype/");
  if(response.status()!==200)throw Error("Live page unavailable");
  await page.locator(".bus-marker").first().waitFor();
  const snapshot=await page.evaluate(async()=>{const{state}=await import("./assets/js/state.js");return {lines:state.lines.length,stops:state.stops.length,buses:state.buses.length};});
  if(snapshot.lines<9||snapshot.stops<90||snapshot.buses<40)throw Error("Map data incomplete");
  await page.locator("#settings").click();
  await page.getByRole("heading",{name:"Settings"}).waitFor();
  await page.locator('[data-action="settings-back"]').click();
  await page.getByRole("link",{name:"Plan",exact:true}).click();
  await page.locator('input[name="from"]').fill("rrethi 24h");
  await page.locator('input[name="to"]').fill("furra saranda");
  await page.locator('#journey-form button[type="submit"]').click();
  await page.locator('[data-line="1>4"]').waitFor({timeout:10000});
  await page.getByRole("link",{name:"Ticket",exact:true}).click();
  if(!(await page.locator("#page").innerText()).includes("Valid until midnight"))throw Error("Daily ticket text missing");
  if(errors.length)throw Error(errors.join("; "));
  return {status:response.status(),snapshot,transferSearch:true,settings:true,errors};
};