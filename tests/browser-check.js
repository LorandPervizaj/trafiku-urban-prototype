async (page) => {
  const results=[],errors=[];
  const check=(ok,name)=>{if(!ok)throw Error(name);results.push(name);};
  page.on("pageerror",e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.setViewportSize({width:390,height:844});
  await page.goto("http://127.0.0.1:8080/");
  await page.evaluate(()=>localStorage.removeItem("trafiku-urban-v1"));
  await page.reload();
  await page.locator(".bus-marker").first().waitFor();
  check(await page.locator("#map-screen").isVisible(),"Map opens first");
  check(await page.locator("#stop-sheet").isHidden(),"Map opens without a bottom card");
  check((await page.locator("#navigation a").count())===3,"Three bottom tabs");
  const counts=await page.evaluate(async()=>{
    const {state}=await import("./assets/js/state.js");
    return {lines:state.lines.length,buses:state.buses.length};
  });
  check(counts.lines>=9,"Nine mapped operator lines");
  check(counts.buses>=40,"Expanded simulated fleet");
  await page.locator('[data-filter="all"]').click();
  check((await page.locator(".bus-marker").count())===0,"All toggles every bus off");
  await page.locator('[data-filter="all"]').click();
  check((await page.locator(".bus-marker").count())===counts.buses,"All toggles every bus on");
  await page.locator('[data-lang="sq"]').click();
  check(await page.getByRole("link",{name:"Harta",exact:true}).count()===1,"Albanian navigation");
  await page.locator('[data-lang="en"]').click();
  check(await page.getByRole("link",{name:"Map",exact:true}).count()===1,"English navigation");
  await page.locator(".bus-marker").first().click();
  check(await page.locator("#stop-sheet").isVisible(),"Bus opens selected details");
  await page.locator('[data-action="dismiss-sheet"]').click();
  check(await page.locator("#stop-sheet").isHidden(),"Selected details close");
  await page.locator("#settings").click();
  check(await page.locator("#language").count()===1,"Settings language selector");
  await page.locator("#language").selectOption("sq");
  check(await page.getByRole("heading",{name:"Personalizo aplikacionin"}).count()===1,"Settings translate live");
  await page.locator("#language").selectOption("en");
  await page.locator('[data-action="close-settings"]').click();
  await page.getByRole("link",{name:"Ticket",exact:true}).click();
  const ticket=await page.locator("#page").innerText();
  for(const price of ["€0.60","€0.80","€1.00","€1.20","€5.00","€6.00"])
    check(ticket.includes(price),"Official fare "+price);
  const wallet=page.getByRole("link",{name:"Open Kuleta Digjitale"});
  check((await wallet.getAttribute("href"))==="https://kd.pbc.group/index","Wallet handoff");
  await page.getByRole("link",{name:"Plan",exact:true}).click();
  const journey=await page.evaluate(async()=>{
    const {state}=await import("./assets/js/state.js");
    const names=[...new Set(state.stops.filter(s=>s.properties.lines.includes("4")).map(s=>s.properties.name))];
    return {from:names[0],to:names.at(-1)};
  });
  await page.locator('input[name="from"]').fill(journey.from);
  await page.locator('input[name="to"]').fill(journey.to);
  await page.getByRole("button",{name:"Find routes"}).click();
  await page.locator('[data-line="4"]').click();
  await page.getByRole("button",{name:"Save journey",exact:true}).click();
  await page.reload();
  await page.getByRole("link",{name:"Plan",exact:true}).click();
  await page.getByRole("button",{name:"See all"}).click();
  check((await page.locator('[data-saved]').count())===1,"Saved journey survives reload");
  check(errors.length===0,"No browser errors: "+errors.join(","));
  return {results,counts};
};
