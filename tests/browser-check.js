async (page) => {
  const errors=[],results=[];
  page.on("pageerror",e=>errors.push(e.message));
  const check=(condition,name)=>{if(!condition)throw Error(name);results.push(name);};
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:"reduce"});
  await page.goto("http://127.0.0.1:8080/");
  await page.evaluate(()=>localStorage.removeItem("trafiku-urban-v1"));
  await page.reload();
  await page.locator(".bus-marker").first().waitFor();
  check(await page.locator("#stop-sheet").isHidden(),"No default stop panel");
  const data=await page.evaluate(async()=>{const {state}=await import("./assets/js/state.js");return {stops:state.stops.length,lines:state.lines.length,buses:state.buses.length};});
  check(data.stops>=90&&data.lines>=9,"Transit data and bus markers loaded");
  await page.locator('[data-filter="all"]').click();
  check(await page.locator('[data-filter="all"]').innerText()==="All","All toggle switches to All");
  check(await page.locator(".bus-marker").count()===0,"All hides fleet");
  await page.locator('[data-filter="all"]').click();
  check(await page.locator('[data-filter="all"]').innerText()==="None","All toggle switches to None");
  check(await page.locator(".bus-marker").count()===data.buses,"Fleet restored");
  await page.locator('[data-lang="sq"]').click();
  check(await page.locator('[data-filter="all"]').innerText()==="Asnjë","Albanian filter label");
  await page.locator('[data-lang="en"]').click();
  await page.locator("#settings").click();
  await page.getByRole("heading",{name:"Settings"}).waitFor();
  check(page.url().endsWith("#settings"),"Settings opens inside app");
  await page.locator("#language").selectOption("sq");
  check(await page.getByRole("heading",{name:"Cilësimet"}).isVisible(),"Settings translate");
  await page.locator("#language").selectOption("en");
  await page.locator('[data-action="settings-back"]').click();
  await page.locator("#map").waitFor();
  await page.getByRole("link",{name:"Plan",exact:true}).click();
  await page.locator('input[name="from"]').fill("rrethi 24h");
  await page.locator('input[name="to"]').fill("furra saranda");
  await page.locator('#journey-form button[type="submit"]').click();
  await page.locator('[data-line="1>4"]').waitFor({timeout:10000});
  check(true,"Rrethi 24h to Furra Saranda offers transfer");
  await page.locator('[data-line="1>4"]').click();
  check((await page.locator("#page").innerText()).includes("Change from line 1 to 4"),"Transfer details visible");
  await page.locator('[data-action="save"]').click();
  await page.reload();
  await page.getByRole("link",{name:"Plan",exact:true}).click();
  await page.getByRole("button",{name:"See all"}).click();
  check((await page.locator("[data-saved]").count())===1,"Saved journey persists");
  await page.getByRole("link",{name:"Ticket",exact:true}).click();
  check((await page.locator("#page").innerText()).includes("Valid until midnight"),"Daily ticket valid until midnight");
  check(await page.locator(".wallet-official-icon img").count()===1,"Official wallet artwork");
  check((await page.getByRole("link",{name:"Open Kuleta Digjitale"}).getAttribute("href"))==="https://kd.pbc.group/index","Wallet handoff");
  check(errors.length===0,"No browser errors: "+errors.join("; "));
  return {results,data};
};